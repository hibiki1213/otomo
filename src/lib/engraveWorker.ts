/**
 * The engraving itself, in a worker: Verovio takes seconds over a large
 * score and would freeze the window on the main thread. `engrave.ts` is the
 * other end; requests are done one at a time, in the order they came.
 */
import createVerovioModule from "verovio/wasm";
import { VerovioToolkit, enableLogToBuffer } from "verovio/esm";
import type { Engraved, EngraveOptions, EngraveReply, EngraveRequest } from "./engrave";

const PAPER_MM: Record<EngraveOptions["paper"], [number, number]> = {
  a4: [210, 297],
  letter: [215.9, 279.4],
};

/** Verovio's page options count tenths of a millimetre (its A4 is 2100 × 2970). */
const UNITS_PER_MM = 10;
/** The SVG `viewBox` is ten times finer again. */
const VIEWBOX_PER_MM = 100;

let loading: Promise<VerovioToolkit> | undefined;

/** One toolkit for the worker's lifetime; every engrave resets its options. */
function toolkit(): Promise<VerovioToolkit> {
  loading ??= createVerovioModule()
    .then((module) => {
      // Keep warnings out of the console; they are read back on failure.
      enableLogToBuffer(true, module);
      return new VerovioToolkit(module);
    })
    .catch((e) => {
      loading = undefined;
      throw e;
    });
  return loading;
}

let queue: Promise<void> = Promise.resolve();

addEventListener("message", (e: MessageEvent<EngraveRequest>) => {
  const { id, musicxml, opts } = e.data;
  queue = queue.then(async () => {
    let reply: EngraveReply;
    try {
      reply = { id, engraved: engraveWith(await toolkit(), musicxml, opts) };
    } catch (err) {
      reply = { id, error: err instanceof Error ? err.message : String(err) };
    }
    postMessage(reply);
  });
});

function engraveWith(tk: VerovioToolkit, musicxml: string, opts: EngraveOptions): Engraved {
  const [widthMm, heightMm] = PAPER_MM[opts.paper];

  // MusicXML goes through MEI first: that is where the title block,
  // condensing and label widths are set (see `fixMei`).
  tk.resetOptions();
  tk.setOptions({ breaks: "none" });
  if (!tk.loadData(musicxml)) throw new Error(`Verovio could not read the score: ${tk.getLog().trim()}`);
  const mei = fixMei(tk.getMEI(), musicxml, opts.kind === "score");
  const staves = (mei.match(/<staffDef\b/g) ?? []).length;

  tk.resetOptions();
  tk.setOptions(layoutOptions(opts, widthMm, heightMm, staves));
  if (!tk.loadData(mei)) throw new Error(`Verovio could not lay out the score: ${tk.getLog().trim()}`);

  const count = tk.getPageCount();
  const pages: string[] = [];
  let fontSeen = false;
  for (let page = 1; page <= count; page++) {
    let svg = tk.renderToSVG(page, false);
    // The SMuFL text font rides along as an @font-face on every page that
    // uses it; pdf_write reads it from whichever page has it, so one copy is enough.
    if (fontSeen) svg = svg.replace(FONT_STYLE, "");
    else fontSeen = FONT_STYLE.test(svg);
    // Verovio numbers later pages in their header; ours go in the footer.
    if (page > 1) svg = removeElement(svg, 'class="pgHead autogenerated"');
    if (count > 1) svg = addPageNumber(svg, page, widthMm, heightMm);
    pages.push(svg);
  }
  return { pages, widthMm, heightMm };
}

function layoutOptions(opts: EngraveOptions, widthMm: number, heightMm: number, staves: number) {
  const mm = (v: number) => Math.round(v * UNITS_PER_MM);
  return {
    pageWidth: mm(widthMm),
    pageHeight: mm(heightMm),
    pageMarginTop: mm(10),
    // The page number sits in the bottom margin (see addPageNumber).
    pageMarginBottom: mm(14),
    pageMarginLeft: mm(12),
    pageMarginRight: mm(12),
    // Staff size: `unit` is half a staff space in tenths of a millimetre.
    // Changing it rather than `scale` keeps the margins in millimetres.
    unit: staffUnit(opts.kind, staves),
    breaks: "auto",
    // A last page holding a single bar wastes a sheet.
    breaksNoWidow: true,
    justifyVertically: true,
    // Title, subtitle and composer on page 1. The "auto" footer is
    // Verovio's logo, so there is none.
    header: "auto",
    footer: "none",
    // Full scores drop staves that rest for a whole system. The first system
    // always shows every staff (`condenseFirstPage` off), and the MEI says to
    // condense even without bracketed groups (see fixMei).
    condense: opts.kind === "score" ? "auto" : "none",
    transposeToSoundingPitch: opts.concertPitch ?? false,
    // Glyphs in text (the note in "♩ = 120") use the music font; embedding
    // it is how pdf_write gets hold of it.
    smuflTextFont: "embedded",
    // No indentation: a third less to send to pdf_write.
    svgFormatRaw: true,
  };
}

/**
 * Half a staff space in tenths of a millimetre. A part gets Verovio's
 * default 7.2 mm staff; a score gets smaller the more staves it has, so that
 * an orchestra still fits two systems on a page.
 */
function staffUnit(kind: EngraveOptions["kind"], staves: number): number {
  if (kind === "part") return 9;
  if (staves <= 4) return 7.5;
  if (staves <= 8) return 6.5;
  if (staves <= 16) return 5.5;
  return 4.5;
}

const FONT_STYLE = /<style type="text\/css">\s*@font-face[\s\S]*?<\/style>/;

/** East Asian wide characters: kana, kanji, hangul, full-width forms. */
const WIDE = /[ᄀ-ᅟ⺀-〾ぁ-㏿㐀-䶿一-鿿가-힣豈-﫿︰-﹏＀-｠￠-￦]/g;

/**
 * What Verovio's MusicXML import leaves out of the MEI it lays out from:
 * - it keeps `<movement-title>` over `<work-title>`, and puts the composer
 *   where the title block does not look, so the title statement is rebuilt;
 * - it condenses only scores with more than one bracket or brace, so a full
 *   score is marked for condensing outright;
 * - it measures text with Times' widths, taking a kana or kanji for half an
 *   em where it sets a whole one, so Japanese part names would hang out of
 *   the margin and lyrics sit right of their notes and crowd each other.
 *   They are padded with a no-break space (a quarter em) per half em short:
 *   names on the left, the blank end of right-aligned text, and lyrics on
 *   the right, so that the visible part is what gets centred.
 */
function fixMei(mei: string, musicxml: string, condense: boolean): string {
  const work = xmlText(musicxml, "work-title");
  const movement = xmlText(musicxml, "movement-title");
  const titles = [work || movement, work && movement !== work ? movement : ""];
  const creator = (type: string) => xmlText(musicxml, "creator", `type="${type}"`);
  const stmt =
    "<titleStmt>" +
    (titles[0] ? `<title type="main">${escapeXml(titles[0])}</title>` : "<title/>") +
    (titles[1] ? `<title type="subordinate">${escapeXml(titles[1])}</title>` : "") +
    ["composer", "lyricist", "arranger"]
      .map((role) => creator(role) && `<${role}>${escapeXml(creator(role))}</${role}>`)
      .join("") +
    "</titleStmt>";
  let out = mei.replace(/<titleStmt\b[^>]*?(?:\/>|>[\s\S]*?<\/titleStmt>)/, stmt);
  if (condense) out = out.replace(/<scoreDef\b(?![^>]*\boptimize=)/, '<scoreDef optimize="true"');
  const pad = (text: string) => " ".repeat(2 * (text.match(WIDE)?.length ?? 0));
  out = out.replace(/(<label(?:Abbr)?\b[^>]*>)([^<]+)(?=<\/label)/g, (_, open: string, text: string) => open + pad(text) + text);
  out = out.replace(/(<syl\b[^>]*>)([^<]+)(?=<\/syl>)/g, (_, open: string, text: string) => open + text + pad(text));
  return out;
}

/** The text of the first `<name attrs…>` element, unescaped. */
function xmlText(xml: string, name: string, attr = ""): string {
  const m = new RegExp(`<${name}\\b[^>]*${attr}[^>]*>([^<]*)</${name}>`).exec(xml);
  return m ? unescapeXml(m[1]).trim() : "";
}

function unescapeXml(s: string): string {
  return s.replace(/&(?:#x([0-9a-f]+)|#(\d+)|(\w+));/gi, (all, hex, dec, name) => {
    if (hex) return String.fromCodePoint(parseInt(hex, 16));
    if (dec) return String.fromCodePoint(parseInt(dec, 10));
    return ({ amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" } as Record<string, string>)[name] ?? all;
  });
}

function escapeXml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** Cut the `<g>` carrying `marker` out of the SVG, with everything inside it. */
function removeElement(svg: string, marker: string): string {
  const at = svg.indexOf(marker);
  if (at < 0) return svg;
  const start = svg.lastIndexOf("<g", at);
  const tag = /<(\/?)g\b[^>]*?(\/?)>/g;
  tag.lastIndex = start;
  let depth = 0;
  for (let m; (m = tag.exec(svg)); ) {
    if (!m[2]) depth += m[1] ? -1 : 1;
    if (depth === 0) return svg.slice(0, start) + svg.slice(tag.lastIndex);
  }
  return svg;
}

/** A centred page number, 7 mm above the bottom edge in the bottom margin. */
function addPageNumber(svg: string, page: number, widthMm: number, heightMm: number): string {
  const x = Math.round((widthMm / 2) * VIEWBOX_PER_MM);
  const y = Math.round((heightMm - 7) * VIEWBOX_PER_MM);
  const size = Math.round(3.5 * VIEWBOX_PER_MM);
  const text = `<text class="pageNum" x="${x}" y="${y}" text-anchor="middle" font-size="${size}px">${page}</text>`;
  // Inside the page's own coordinate system, which is in hundredths of a mm.
  return svg.replace(/<svg class="definition-scale"[^>]*>/, (open) => open + text);
}
